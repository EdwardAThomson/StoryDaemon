"""Writer context builder for scene prose generation."""

import logging
from typing import Dict, Any, List, Optional
from pathlib import Path

from ..tools.name_generator import NameGenerator
from ..tools.language_tools import native_speech_from_results, native_speech_section
from .arc_pressure import arc_pressure_guidance_for_writer, beat_target_is_stale
from .language_situation import language_situation, people_of_character, people_of_location

logger = logging.getLogger(__name__)


class WriterContextBuilder:
    """Builds context for the scene writer LLM."""

    def __init__(self, memory_manager, vector_store, config):
        """Initialize writer context builder.

        Args:
            memory_manager: MemoryManager instance
            vector_store: VectorStore instance
            config: Configuration object
        """
        self.memory = memory_manager
        self.vector = vector_store
        self.config = config
        self.name_generator = NameGenerator(
            Path(__file__).parent.parent / "data" / "names",
            languages_file=self._languages_file(memory_manager),
        )

    @staticmethod
    def _languages_file(memory_manager) -> Optional[Path]:
        """The project's per-people name banks, when a world's languages were
        imported; None (and the generator is unchanged) otherwise."""
        try:
            from ..languages_import import bank_file_path
            path = bank_file_path(memory_manager.project_path)
            return path if path.exists() else None
        except Exception:  # a mock memory manager, or no project path
            return None
    
    def build_writer_context(
        self,
        plan: Dict[str, Any],
        execution_results: Dict[str, Any],
        project_state: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Build context dictionary for writer prompt.
        
        Args:
            plan: The plan generated by planner
            execution_results: Results from plan execution
            project_state: Current project state
        
        Returns:
            Dictionary with all context variables for writer prompt
        """
        # Extract basic info
        novel_name = project_state.get("novel_name", "Untitled Novel")
        current_tick = project_state.get("current_tick", 0)
        scene_intention = plan.get("scene_intention", "Continue the story")
        key_change = plan.get("key_change", "Advance the plot")
        progress_milestone = plan.get("progress_milestone", "")
        progress_step = plan.get("progress_step", "")
        pov_character_id = plan.get("pov_character", "")
        location_id = plan.get("target_location")
        scene_mode = plan.get("scene_mode", "")
        palette_shift = plan.get("palette_shift", "")
        transition_path = plan.get("transition_path", "")
        dialogue_targets = plan.get("dialogue_targets", "")
        
        # Get POV character details
        pov_character_name, pov_character_details = self._get_character_details(
            pov_character_id, project_state
        )
        
        # Get location details
        location_name, location_details = self._get_location_details(location_id)

        # The POV character's language (an imported world's constructed
        # languages): one line ("speaks Quqo, related to Gaipo"), the scene's
        # language situation (who here can follow whom) and the native speech
        # this tick's plan requested through language.phrase/language.word.
        # Nothing else about the languages reaches the writer. It rides the
        # character-details slot rather than a new template placeholder, so
        # hand-built writer contexts keep rendering.
        languages_imported = bool(((project_state or {}).get("world") or {}).get("languages"))
        pov_people = self._pov_people(pov_character_id, location_id)
        languages_section = self._languages_section(project_state, pov_people)
        situation = self._language_situation(
            project_state, pov_people, pov_character_id, pov_character_name,
            location_id, plan, execution_results)
        native_speech = native_speech_from_results(execution_results) if languages_imported else []
        language_block = "\n".join(part for part in (
            languages_section, situation.get("line", ""), native_speech_section(native_speech)) if part)
        if language_block:
            pov_character_details = f"{pov_character_details}\n\n{language_block}"
        
        # Format recent context with full text for immediate scenes
        full_text_count = self.config.get('generation.full_text_scenes_count', 2)
        summary_count = self.config.get('generation.summary_scenes_count', 3)
        recent_context = self._format_recent_context(
            full_text_count=full_text_count,
            summary_count=summary_count
        )
        
        # Format tool results
        tool_results_summary = self._format_tool_results(execution_results)
        
        # Length coordination (Phase 3, segment plumbing for the block DSL): the
        # plan's optional scene_length maps to an explicit word target, stated in
        # the prompt AND used by the writer to size the request ceiling, so the
        # instructed length and the allowed length finally agree.
        scene_length_guidance, word_target = self._get_length_guidance(plan)

        # Scene skeleton (Slice 4 of the block DSL, experimental, gated by
        # generation.enable_scene_skeleton). The plan section rides the
        # length-guidance slot, following the sacred-finale precedent: no new
        # template placeholder, so hand-built writer contexts keep working.
        scene_skeleton = self._build_scene_skeleton(plan, word_target,
                                                    current_tick)
        if scene_skeleton:
            from .scene_skeleton import skeleton_prompt_section
            scene_length_guidance = (
                scene_length_guidance + skeleton_prompt_section(scene_skeleton)
            )

        # Format plot beat section (Phase 5)
        plot_beat_section = self._format_plot_beat_section(plan)

        # Arc-pressure: firm tension target for the writer (Phase 3). Suppressed when
        # a plot beat carries a fresh tension_target (the beat section governs then);
        # a stale beat target yields to the schedule (see _build_arc_pressure_section).
        arc_pressure_section = self._build_arc_pressure_section(plan, current_tick)

        # Sacred finale (Phase 3): the ending-mode instruction rides the same prompt
        # slot as arc pressure (no new template placeholder, so hand-built writer
        # contexts elsewhere keep working). Present only when the agent marked the
        # plan with finale_mode on the finale tick.
        finale_section = self._build_finale_section(plan)
        if finale_section:
            arc_pressure_section = (
                f"{arc_pressure_section}\n\n{finale_section}"
                if arc_pressure_section else finale_section
            )

        # Cast roster + a pool of pre-minted names for any new character (Phase 1 grounding)
        existing_characters, approved_new_names = self._build_cast_and_name_pool(
            project_state, pov_character_id, pov_people
        )

        return {
            "novel_name": novel_name,
            "current_tick": current_tick,
            "scene_intention": scene_intention,
            "key_change": key_change,
            "progress_milestone": progress_milestone,
            "progress_step": progress_step,
            "plot_beat_section": plot_beat_section,
            "arc_pressure_section": arc_pressure_section,
            "scene_mode": scene_mode,
            "palette_shift": palette_shift,
            "transition_path": transition_path,
            "dialogue_targets": dialogue_targets,
            "pov_character_id": pov_character_id,
            "pov_character_name": pov_character_name,
            "pov_character_details": pov_character_details,
            "location_id": location_id,
            "location_name": location_name,
            "location_details": location_details,
            "recent_context": recent_context,
            "tool_results_summary": tool_results_summary,
            "scene_length_guidance": scene_length_guidance,
            "word_target": word_target,
            "scene_skeleton": scene_skeleton,
            "existing_characters": existing_characters,
            "approved_new_names": approved_new_names,
            "languages_section": languages_section,
            "languages_imported": languages_imported,
            "language_situation": situation,
            "native_speech": native_speech,
            "pov_people": pov_people or "",
        }

    def _pov_people(self, pov_character_id: Optional[str],
                    location_id: Optional[str]) -> Optional[str]:
        """Which people the POV character belongs to, by worldgen id or name.

        The character's own record wins (``metadata.worldgen.people`` set by
        character.generate, or a free-text ``metadata.affiliation``); failing
        that, the realm or faction that holds the scene's location, which an
        imported settlement or world carries. None when neither says.
        """
        people = people_of_character(self._load_character(pov_character_id))
        if people:
            return people
        return people_of_location(self._load_location(location_id))

    def _load_character(self, character_id: Optional[str]):
        try:
            return self.memory.load_character(character_id) if character_id else None
        except Exception:
            return None

    def _load_location(self, location_id: Optional[str]):
        try:
            return self.memory.load_location(location_id) if location_id else None
        except Exception:
            return None

    def _language_situation(self, project_state: Dict[str, Any], pov_people: Optional[str],
                            pov_character_id: Optional[str], pov_character_name: str,
                            location_id: Optional[str], plan: Dict[str, Any],
                            execution_results: Dict[str, Any]) -> Dict[str, Any]:
        """Who in this scene can follow whom (agent/language_situation.py).

        The other parties are the location's realm or faction and the
        characters the plan puts in the room: the dialogue targets'
        participants and any character created by this tick's plan. Never
        raises; an unknown situation is an empty line.
        """
        block = ((project_state or {}).get("world") or {}).get("languages")
        if not block:
            return language_situation(None, None, [])
        try:
            others: List[tuple] = []
            location = self._load_location(location_id)
            if location is not None:
                others.append(("the people here", people_of_location(location)))
            for character in self._present_characters(plan, execution_results, pov_character_id):
                others.append((character.display_name, people_of_character(character)))
            return language_situation(block, pov_people, others,
                                      resolve=self.name_generator.resolve_people,
                                      pov_label=pov_character_name)
        except Exception as e:  # never cost a scene
            logger.warning(f"Could not compute the language situation: {e}")
            return language_situation(None, None, [])

    def _present_characters(self, plan: Dict[str, Any], execution_results: Dict[str, Any],
                            pov_character_id: Optional[str]) -> list:
        """Characters the plan puts in the scene besides the POV: dialogue
        participants (ids or names) and characters created this tick."""
        wanted: List[str] = []
        targets = (plan or {}).get("dialogue_targets")
        if isinstance(targets, dict):
            participants = targets.get("participants") or targets.get("characters") or []
            if isinstance(participants, str):
                participants = [p.strip() for p in participants.replace(";", ",").split(",")]
            wanted.extend(str(p) for p in participants if p)
        for action in (execution_results or {}).get("actions_executed") or []:
            if action.get("tool") == "character.generate":
                cid = (action.get("result") or {}).get("character_id")
                if cid:
                    wanted.append(str(cid))
        if not wanted:
            return []
        roster = {}
        for cid in self.memory.list_characters():
            character = self._load_character(cid)
            if character is not None:
                roster[cid] = character
        found, seen = [], set()
        for ref in wanted:
            key = ref.strip().lower()
            match = roster.get(ref.strip())
            if match is None:
                match = next((c for c in roster.values()
                              if key in (c.display_name.lower(), c.full_name.lower())), None)
            if match is None or match.id == pov_character_id or match.id in seen:
                continue
            seen.add(match.id)
            found.append(match)
        return found

    def _languages_section(self, project_state: Dict[str, Any],
                           pov_people: Optional[str]) -> str:
        """The compact Languages line for the POV's people, or ''."""
        block = ((project_state or {}).get("world") or {}).get("languages")
        if not block or not pov_people:
            return ""
        try:
            from ..languages_import import languages_line
            people_id = self.name_generator.resolve_people(pov_people) or pov_people
            return languages_line(block, people_id)
        except Exception as e:  # never cost a scene
            logger.warning(f"Could not build the languages line: {e}")
            return ""

    def _build_arc_pressure_section(self, plan: Dict[str, Any], current_tick: int) -> str:
        """Firm arc-pressure tension instruction for the writer, or "" when not applicable.

        Suppressed when the plan's plot beat carries a fresh ``tension_target``: that
        target is injected by ``_format_plot_beat_section`` and must not be doubled.
        A STALE beat target (a transition-step or more off the current curve target,
        ``beat_target_is_stale``) does NOT suppress: the beat was consumed far off its
        scheduled position, so the schedule governs and this section renders alongside
        the beat section's own target line, explicitly current (Phase 3, 2026-07-10
        report addendum: the tension floor cap in contracts/authoring.py makes the
        observed wedge unlikely to recur; this is the backstop for any other cause of
        staleness). Fresh-beat precedence is unchanged.
        """
        beat = plan.get("plot_beat") or {}
        beat_target = beat.get("tension_target")
        if beat_target is not None and not beat_target_is_stale(
            beat_target, current_tick, self.config
        ):
            return ""
        return arc_pressure_guidance_for_writer(current_tick, self.config)

    def _build_scene_skeleton(self, plan: Dict[str, Any], word_target: int,
                              current_tick: int) -> Optional[List[str]]:
        """Typed paragraph plan for this scene (Slice 4, experimental).

        Gated by generation.enable_scene_skeleton (default off). A plan that
        already carries a valid scene_skeleton wins; otherwise one is sampled
        from the masters' block grammar, sized by the scene's word target and
        conditioned on the tension target (a fresh beat target first, else
        the arc-pressure schedule). Never raises: a skeleton failure must not
        cost the scene, it just loses the guidance.
        """
        if not self.config.get('generation.enable_scene_skeleton', False):
            return None
        try:
            from .arc_pressure import compute_target_tension
            from .scene_skeleton import generate_skeleton

            provided = plan.get("scene_skeleton")
            if provided:
                return list(provided)
            beat = plan.get("plot_beat") or {}
            tension = beat.get("tension_target")
            if tension is None or beat_target_is_stale(
                tension, current_tick, self.config
            ):
                tension = compute_target_tension(current_tick, self.config)
            return generate_skeleton(word_target, tension=tension)
        except Exception as e:
            import logging
            logging.getLogger(__name__).warning(
                f"scene skeleton generation failed; writing without one: {e}")
            return None

    def _build_finale_section(self, plan: Dict[str, Any]) -> str:
        """Ending-mode instruction for the story's final scene (Phase 3 sacred finale).

        The agent sets ``plan["finale_mode"]`` ("settled" or "hook") only on the
        finale tick; every other plan renders "". Never raises: a failure here
        must not cost the scene, it just loses the instruction.
        """
        mode = plan.get("finale_mode")
        if not mode:
            return ""
        try:
            from .finale import ending_instruction
            return ending_instruction(mode)
        except Exception:
            return ""

    def _build_cast_and_name_pool(self, project_state: Dict[str, Any],
                                  pov_character_id: str,
                                  pov_people: Optional[str] = None) -> tuple[str, str]:
        """List the existing cast and mint a small pool of unused, grounded names.

        The writer is told to use cast names or, only when a new character truly
        needs a name, one of the pooled names — so it never invents one. When
        the POV's people has a language bank, half the pool comes from it, so
        a walk-on in that realm can carry one of its own names.
        """
        cast_lines = []
        for cid in sorted(self.memory.list_characters()):
            c = self.memory.load_character(cid)
            if not c:
                continue
            self.name_generator.register_used_name(c.full_name)
            marker = " (POV)" if cid == pov_character_id else ""
            cast_lines.append(f"- {c.display_name} ({c.role}){marker}")
        existing_characters = "\n".join(cast_lines) if cast_lines else "(none yet)"

        genre = (project_state.get("story_foundation") or {}).get("genre") or "scifi"
        people_id = self.name_generator.resolve_people(pov_people) if pov_people else None
        pool = []
        for i in range(4):
            try:
                gender = "male" if len(pool) % 2 == 0 else "female"
                affiliation = people_id if (people_id and i < 2) else None
                minted = self.name_generator.generate_name(
                    gender=gender, genre=genre, affiliation=affiliation)
                pool.append(minted["full_name"])
            except ValueError:
                break
        approved_new_names = "\n".join(f"- {n}" for n in pool) if pool else "(use a role descriptor instead)"
        return existing_characters, approved_new_names
    
    def _protagonist_fallback(self, project_state):
        """No longer a fallback: a missing POV character is now an error.

        This used to parse a name out of the foundation's free text when the
        plan's character id resolved to nothing. That silently substituted a
        phantom: a name with no entity behind it, no id, no memory record, no
        relationships, nothing the fact extractor could update or the vector
        store retrieve. Eight scenes were written that way before anyone
        noticed, and the naming contract pointed at an empty pool throughout.

        The protagonist is now minted in Python at project creation
        (cli/protagonist.py), so reaching here means a real fault: a project
        created before that existed, or a character deleted from memory.
        Failing loudly is the point.
        """
        foundation = (project_state or {}).get("story_foundation") or {}
        archetype = (foundation.get("protagonist_archetype") or "").strip()
        raise ValueError(
            "No POV character could be resolved for this scene. The plan's "
            "character id does not match any character in memory, and the "
            "writer will not be handed a name with no entity behind it. "
            f"Foundation protagonist: {archetype or '(none)'}. "
            "For a project created before protagonists were minted at "
            "creation, run a tick that generates a character first."
        )

    def _get_character_details(
        self, character_id: str, project_state: Optional[Dict[str, Any]] = None
    ) -> tuple[str, str]:
        """Get character name and formatted details.

        Args:
            character_id: Character ID
            project_state: Project state (for the missing-entity fallback)

        Returns:
            Tuple of (character_name, formatted_details)
        """
        if not character_id:
            return self._protagonist_fallback(project_state)

        character = self.memory.load_character(character_id)
        if not character:
            return self._protagonist_fallback(project_state)
        
        # Format character details
        details = f"**Name:** {character.display_name} (full name: {character.full_name})\n"
        details += f"**ID:** {character.id}\n\n"
        
        if character.description:
            details += f"**Description:** {character.description}\n\n"
        
        if character.personality and character.personality.core_traits:
            details += f"**Personality:** {', '.join(character.personality.core_traits)}\n\n"
        
        if character.backstory:
            details += f"**Backstory:** {character.backstory}\n\n"
        
        if character.current_state.goals:
            details += f"**Goals:** {', '.join(character.current_state.goals)}\n\n"
        
        return character.display_name, details.strip()
    
    def _get_location_details(self, location_id: Optional[str]) -> tuple[str, str]:
        """Get location name and formatted details.
        
        Args:
            location_id: Location ID or None
        
        Returns:
            Tuple of (location_name, formatted_details)
        """
        if not location_id:
            return "Unknown Location", "Location to be determined during scene."
        
        location = self.memory.load_location(location_id)
        if not location:
            # Same guarantee as the POV fallback: a raw id ("L0") must never
            # reach the prose as a place name.
            return "Unknown Location", "Location to be determined during scene."
        
        # Format location details
        details = f"**Name:** {location.name}\n"
        details += f"**ID:** {location.id}\n\n"
        
        if location.description:
            details += f"**Description:** {location.description}\n\n"
        
        if location.type:
            details += f"**Type:** {location.type}\n\n"
        
        if location.atmosphere:
            details += f"**Atmosphere:** {location.atmosphere}\n\n"
        
        if location.features:
            details += f"**Features:** {', '.join(location.features)}\n\n"
        
        return location.name, details.strip()
    
    def _format_recent_context(self, full_text_count: int = 2, summary_count: int = 3) -> str:
        """Format recent context with full text for immediate scenes.
        
        Args:
            full_text_count: Number of recent scenes to include as full text
            summary_count: Number of older scenes to include as summaries
        
        Returns:
            Formatted context with full text + summaries
        """
        # Get all scene IDs
        scene_ids = self.memory.list_scenes()
        
        if not scene_ids:
            return "This is the first scene of the novel."
        
        context_parts = []
        
        # Calculate which scenes get full text vs summaries
        total_scenes = len(scene_ids)
        
        # Get scenes for summaries (older scenes)
        summary_start = max(0, total_scenes - full_text_count - summary_count)
        summary_end = max(0, total_scenes - full_text_count)
        summary_ids = scene_ids[summary_start:summary_end] if summary_end > summary_start else []
        
        # Get scenes for full text (most recent)
        full_text_ids = scene_ids[-full_text_count:] if total_scenes >= full_text_count else scene_ids
        
        # Add summary scenes first (if any)
        if summary_ids:
            context_parts.append("## Earlier Scenes (Summaries)\n")
            for scene_id in summary_ids:
                scene = self.memory.load_scene(scene_id)
                if scene:
                    context_parts.append(f"**Scene {scene.tick}: {scene.title}**")
                    if scene.summary:
                        # Format summary bullets
                        if isinstance(scene.summary, list):
                            for bullet in scene.summary:
                                context_parts.append(f"- {bullet}")
                        else:
                            context_parts.append(scene.summary)
                    context_parts.append("")  # Blank line
            context_parts.append("")  # Extra blank line between sections
        
        # Add full text scenes (most recent)
        if full_text_ids:
            context_parts.append("## Recent Scenes (Full Text)\n")
            for scene_id in full_text_ids:
                scene = self.memory.load_scene(scene_id)
                if scene:
                    # Load the actual scene markdown file
                    # Scene IDs are like "S000", "S001", etc.
                    scene_number = scene_id[1:]  # Remove 'S' prefix
                    scene_file = self.memory.project_path / "scenes" / f"scene_{scene_number}.md"
                    
                    if scene_file.exists():
                        scene_text = scene_file.read_text(encoding='utf-8')
                        context_parts.append(f"**Scene {scene.tick}: {scene.title}**\n")
                        context_parts.append(scene_text.strip())
                        context_parts.append("\n---\n")
                    else:
                        # Fallback to summary if file doesn't exist
                        context_parts.append(f"**Scene {scene.tick}: {scene.title}**")
                        if scene.summary:
                            if isinstance(scene.summary, list):
                                for bullet in scene.summary:
                                    context_parts.append(f"- {bullet}")
                            else:
                                context_parts.append(scene.summary)
                        context_parts.append("")
        
        if not context_parts:
            return "This is the first scene of the novel."
        
        return "\n".join(context_parts).strip()
    
    def _format_tool_results(self, execution_results: Dict[str, Any]) -> str:
        """Format tool execution results into readable summary.
        
        Args:
            execution_results: Results from plan execution
        
        Returns:
            Formatted string summarizing tool results
        """
        if not execution_results:
            return "No tools were executed for this scene."
        
        actions_executed = execution_results.get("actions_executed", [])
        
        if not actions_executed:
            return "No tools were executed for this scene."
        
        summary_parts = []
        
        for action in actions_executed:
            tool_name = action.get("tool", "unknown")
            result = action.get("result", {})
            
            # Format based on tool type
            if tool_name == "memory.search":
                query = action.get("args", {}).get("query", "")
                results = result.get("results", [])
                summary_parts.append(f"- Searched memory for '{query}': Found {len(results)} results")
            
            elif tool_name == "character.generate":
                char_name = result.get("name", "Unknown")
                summary_parts.append(f"- Generated new character: {char_name}")
            
            elif tool_name == "location.generate":
                loc_name = result.get("name", "Unknown")
                summary_parts.append(f"- Generated new location: {loc_name}")
            
            elif tool_name == "relationship.create":
                summary_parts.append(f"- Created new relationship")
            
            elif tool_name == "relationship.update":
                summary_parts.append(f"- Updated relationship")

            elif tool_name in ("language.phrase", "language.word"):
                if result.get("found") and result.get("text"):
                    summary_parts.append(
                        f"- Native speech requested: \u201c{result['text']}\u201d "
                        f"({result.get('english') or result.get('gloss') or ''}, {result.get('language') or ''})")
                else:
                    summary_parts.append(f"- {tool_name} found nothing usable; the scene has no native words")
            
            else:
                summary_parts.append(f"- Executed {tool_name}")
        
        if not summary_parts:
            return "No significant tool results to report."
        
        return "\n".join(summary_parts)
    
    def _get_length_guidance(self, plan: Dict[str, Any]) -> tuple:
        """Length guidance from plan metadata, with an explicit word target.

        Phase 3 (segment plumbing for the block DSL): the root cause of the
        2026-07-11 truncation evidence was that nothing connected the instructed
        length to the allowed length. The guidance now always states a word
        target ("write roughly N words"), and the same target is returned so the
        writer can size the request ceiling from it. With no scene_length in the
        plan, generation.default_scene_length governs ("long" by default).

        Args:
            plan: The plan dictionary

        Returns:
            (guidance_string, word_target) tuple
        """
        from .segments import word_target_for

        metadata = plan.get("metadata") or {}
        scene_length = metadata.get("scene_length", "")
        scene_length = scene_length.lower() if isinstance(scene_length, str) else ""
        word_target = word_target_for(scene_length, self.config)

        flavor = {
            "brief": "Keep this scene brief and focused - a quick moment or transition.",
            "short": "Write a short scene - establish the key moment without extensive detail.",
            "long": "Take your time with this scene - develop it fully with rich detail and depth.",
            "extended": "This is a major scene - write extensively, exploring all nuances and implications.",
        }.get(scene_length, "Develop the scene fully, at its natural pace.")

        return (
            f"\n\n**Length Guidance:** {flavor} Write roughly {word_target} words, "
            f"and bring the scene to a complete ending within that budget.",
            word_target,
        )
    
    def _format_plot_beat_section(self, plan: Dict[str, Any]) -> str:
        """Format plot beat section for writer prompt (Phase 5).
        
        Args:
            plan: The plan dictionary (may contain plot_beat from agent)
        
        Returns:
            Formatted plot beat section or empty string
        """
        # Check if plot_beat was injected by the agent
        plot_beat = plan.get("plot_beat")
        if not plot_beat or not isinstance(plot_beat, dict):
            return ""
        
        description = plot_beat.get("description", "")
        if not description:
            return ""
        
        section = f"\n**🎯 PLOT BEAT TO EXECUTE:** {description}\n"

        # Phase 3 (descent-run4 wedge): the beat's cast and contract reach the
        # writer as canonical NAMES, not bare ids the writer cannot bind to
        # anyone (grounded identity on the contract surface). getattr, not
        # self.memory: callers without a memory fall back to bare ids.
        from ..contracts.authoring import describe_condition, entity_label
        memory = getattr(self, "memory", None)

        # Add additional beat constraints if present
        characters = plot_beat.get("characters_involved", [])
        if characters:
            cast = ", ".join(entity_label(char_id, memory) or char_id for char_id in characters)
            section += f"**Characters who must appear:** {cast}\n"

        location = plot_beat.get("location")
        if location:
            section += f"**Required Location:** {entity_label(location, memory) or location}\n"
        
        tension_target = plot_beat.get("tension_target")
        if tension_target:
            section += f"**Target Tension Level:** {tension_target}/10\n"
        
        plot_threads = plot_beat.get("plot_threads", [])
        if plot_threads:
            section += f"**Advances Plot Threads:** {', '.join(plot_threads)}\n"

        # Beat contract (Phase 3, contracts Slice 1): the writer aims at exactly
        # what the postcondition checker will grade (the tension_scale lesson).
        postconditions = plot_beat.get("postconditions") or []
        if postconditions:
            section += "**This scene must leave the story in a state where:**\n"
            for cond in postconditions:
                section += f"- {describe_condition(cond, memory)}\n"

        section += "\n**THIS BEAT MUST BE ACCOMPLISHED IN THIS SCENE.**\n"

        return section
